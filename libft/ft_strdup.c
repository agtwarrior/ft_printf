#include "libft.h"

char	*ft_strdup(const char *src)
{
	char	*str;
	int		i;
	size_t	len;

	i = 0;
	len = ft_strlen(src);
	str = malloc(sizeof(char) * (len + 1));
	if (!str)
		return (NULL);
	while (src[i])
	{
		str[i] = src[i];
		i++;
	}
	str[i] = '\0';
	return (str);
}
